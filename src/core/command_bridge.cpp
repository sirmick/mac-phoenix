/*
 * command_bridge.cpp - Host-side command dispatcher for controlling Mac OS
 *
 * Read commands (app name, window list, memory) peek Mac memory directly
 * from the 60Hz IRQ — safe because no Toolbox calls are needed.
 *
 * Action commands (launch, quit) are handled by the BridgeINIT, a compiled
 * Retro68 INIT embedded in the emulator binary. At boot, the INIT is
 * allocated via _NewPtrSys and called via Execute68k. It installs a
 * jGNEFilter that polls for command files on the ExtFS "Host" volume.
 *
 * Communication is entirely file-based:
 *   Host writes Host:_bridge_cmd  → INIT reads, executes, deletes
 *   INIT writes Host:_bridge_result → Host reads, returns to API caller
 *
 * No EmulOps. No hand-coded 68k. No mailbox in ScratchMem.
 */


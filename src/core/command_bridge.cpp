/*
 * command_bridge.cpp - Host-side command dispatcher for controlling Mac OS
 *
 * Read commands (app name, window list, memory) peek Mac memory directly
 * from the 60Hz IRQ — safe because no Toolbox calls are needed.
 *
 * Action commands (launch, quit) work through a BridgeINIT that is embedded
 * in the emulator binary and injected at boot. The INIT installs a jGNEFilter
 * that polls for command files on the ExtFS "Host" volume. Communication is
 * entirely file-based — the host writes _bridge_cmd, the INIT reads it,
 * executes the command, and writes _bridge_result.
 *
 * Legacy path: for backward compatibility, the old mailbox + Execute68kTrap
 * approach is kept behind the same code paths but the bridge INIT is preferred
 * when --bridge is enabled.
 */


static const size_t dispatch_offset = 0;
static const size_t call_offset = 0x3C;

void Executor::ROMlib_install_system_routines()
{
    static Ptr code;
    if(!code)
    {
        TheZoneGuard guard(LM(SysZone));
        code = NewPtrSys(sizeof system_routines);
        if(!code)
            return;
        memcpy(code, system_routines, sizeof system_routines);
    }
    LM(SelectorTableDispatch) = (ProcPtr)(code + dispatch_offset);
    LM(CallDetachedPackage) = (ProcPtr)(code + call_offset);
}

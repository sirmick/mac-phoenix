/* MacPhoenix: System routines 7.5.5 keeps in low memory for its own code
 * resources, as 68k code: the selector-table dispatcher at $7B0 and the
 * detached-package call at $668 (see Package.yaml). The bytes are the
 * System's, copied from a 7.5.5 boot (RAM $3656C-$3661F on the reference
 * snapshot); they use only PC-relative branches and absolute low-memory
 * addresses, so they run from anywhere.
 */
#include <base/common.h>
#include <MemoryMgr.h>
#include <Package.h>
#include <mman/mman.h>
#include <rsys/sysroutines.h>

#include <cstring>

using namespace Executor;


std::string inflated(const std::vector<uint8_t> &z, bool *ok, size_t limit = 1 << 20)
{
    std::vector<uint8_t> out;
    *ok = ROMlib_zlib_inflate(z.data(), z.size(), out, limit);
    return std::string(out.begin(), out.end());
}

/* the words the dynamic stream holds: 400 of them, picked by an LCG */
std::string words()
{
    static const char *const w[] = { "movie", "track", "media", "sample", "time",
                                     "base", "atom", "chunk", "frame", "codec" };
    std::string s;
    uint32_t x = 1;
    for(int i = 0; i < 400; i++)
    {
        x = (x * 1103515245u + 12345) & 0x7FFFFFFF;
        if(i)
            s += ' ';
        s += w[(x >> 16) % 10];
    }
    return s;
}


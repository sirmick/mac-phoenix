TEST(Inflate, DynamicHuffman)
{
    bool ok;
    EXPECT_EQ(inflated(dynamic_stream, &ok), words());
    EXPECT_TRUE(ok);
}

TEST(Inflate, DamageAndLimitsAreRefused)
{
    bool ok;
    std::vector<uint8_t> z = dynamic_stream;
    z[z.size() - 1] ^= 1; /* the Adler-32 */
    inflated(z, &ok);
    EXPECT_FALSE(ok);
    z = dynamic_stream;
    z[40] ^= 0x55; /* the codes */
    inflated(z, &ok);
    EXPECT_FALSE(ok);
    inflated(dynamic_stream, &ok, 100); /* more than the limit */
    EXPECT_FALSE(ok);
    inflated({ 0x78, 0x9c }, &ok);
    EXPECT_FALSE(ok);
    inflated({ 0x79, 0x9c, 0x03, 0x00, 0x00, 0x00, 0x00, 0x01 }, &ok); /* not deflate */
    EXPECT_FALSE(ok);
}

/* A movie made in memory, put into a handle, then read back from a
   'cmov' header holding the same 'moov' (stored blocks) */
TEST(Inflate, MovieFromCompressedHeader)
{
    C_EnterMovies();
    Movie m = C_NewMovie(0);
    ASSERT_NE(m, nullptr);
    C_SetMovieTimeScale(m, 600);
    Track t = C_NewMovieTrack(m, 32 << 16, 24 << 16, 0);
    ASSERT_NE(t, nullptr);
    Handle h = NewHandle(0);
    ASSERT_EQ(C_PutMovieIntoHandle(m, h), noErr);
    C_DisposeMovie(m);

    std::vector<uint8_t> moov((uint8_t *)*h, (uint8_t *)*h + GetHandleSize(h));
    std::vector<uint8_t> z = stored(moov.data(), moov.size());
    std::vector<uint8_t> dcom, cmvd, cmov, outer;
    put32(dcom, 12);
    put32(dcom, "dcom"_4);
    put32(dcom, "zlib"_4);
    put32(cmvd, 12 + z.size());
    put32(cmvd, "cmvd"_4);
    put32(cmvd, moov.size());
    cmvd.insert(cmvd.end(), z.begin(), z.end());
    put32(cmov, 8 + dcom.size() + cmvd.size());
    put32(cmov, "cmov"_4);
    cmov.insert(cmov.end(), dcom.begin(), dcom.end());
    cmov.insert(cmov.end(), cmvd.begin(), cmvd.end());
    put32(outer, 8 + cmov.size());
    put32(outer, "moov"_4);
    outer.insert(outer.end(), cmov.begin(), cmov.end());

    SetHandleSize(h, outer.size());
    memcpy(*h, outer.data(), outer.size());
    GUEST<Movie> back;
    ASSERT_EQ(C_NewMovieFromHandle(&back, h, 0, nullptr), noErr);
    EXPECT_EQ(C_GetMovieTimeScale(back), 600);
    EXPECT_EQ(C_GetMovieTrackCount(back), 1);
    GUEST<Fixed> w, hgt;
    C_GetTrackDimensions(C_GetMovieIndTrack(back, 1), &w, &hgt);
    EXPECT_EQ(w, 32 << 16);
    EXPECT_EQ(hgt, 24 << 16);
    C_DisposeMovie(back);

    /* a stream that doesn't inflate to the size 'cmvd' gives */
    outer[outer.size() - 1] ^= 1;
    memcpy(*h, outer.data(), outer.size());
    EXPECT_NE(C_NewMovieFromHandle(&back, h, 0, nullptr), noErr);
    DisposeHandle(h);
}
